export const CATEGORY_ICONS: Readonly<Record<string, TablerIcon>> = Object.fromEntries(
  ENTRIES.map(([key, icon]) => [key, icon]),
)

/** Keys in curated display order (seed icons first). */
export const CATEGORY_ICON_KEYS: readonly string[] = ENTRIES.map(([key]) => key)

/** Shown for keys that are not in the registry. */
export const FALLBACK_CATEGORY_ICON: TablerIcon = IconCircleDot

const SEARCH_TEXT = new Map(ENTRIES.map(([key, , keywords]) => [key, normalizeSearch(`${key.replaceAll('-', ' ')} ${keywords}`)]))

/** Lower-case, accent-free text for matching (`Biberón` → `biberon`). */
export function normalizeSearch(text: string): string {
  return text
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .trim()
}

export function categoryIcon(key: string | null | undefined): TablerIcon {
  return (key ? CATEGORY_ICONS[key] : undefined) ?? FALLBACK_CATEGORY_ICON
}

/** Registry keys whose key or ES/EN keywords contain every word of `query` (accent-insensitive). */
export function searchCategoryIcons(query: string): string[] {
  const words = normalizeSearch(query).split(/\s+/).filter(Boolean)
  if (words.length === 0) return [...CATEGORY_ICON_KEYS]
  return CATEGORY_ICON_KEYS.filter((key) => {
    const text = SEARCH_TEXT.get(key) ?? key
    return words.every((word) => text.includes(word))
  })
}
